const supportedLocales = [
  { code: 'en', labelKey: 'common.english' },
  { code: 'zh-Hant', labelKey: 'common.traditionalChinese' }
]

function normalizeLocale(value) {
  return supportedLocales.some((item) => item.code === value) ? value : 'zh-Hant'
}

export const useLocaleStore = defineStore('locale', () => {
  const stored = typeof localStorage === 'undefined' ? 'zh-Hant' : localStorage.getItem('sf-locale')
  const locale = ref(normalizeLocale(stored || 'zh-Hant'))

  function apply(value) {
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', value === 'zh-Hant' ? 'zh-Hant' : 'en')
    }
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('sf-locale', value)
    }
  }

  function setLocale(value) {
    locale.value = normalizeLocale(value)
  }

  function toggleLocale() {
    locale.value = locale.value === 'en' ? 'zh-Hant' : 'en'
  }

  function t(key, params = {}) {
    const table = messages[locale.value] || messages['zh-Hant']
    const fallback = messages.en || {}
    const raw = table[key] || fallback[key] || key
    return raw.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '')
  }

  watch(locale, apply, { immediate: true })

  return { locale, supportedLocales, setLocale, toggleLocale, t }
})
